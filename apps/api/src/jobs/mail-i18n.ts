const DICTS: Record<MailLang, Record<Keys, string>> = { en, fr, nl, de, es };

export type MailT = (key: Keys, vars?: Record<string, string | number>) => string;

export function mailLang(language: string | null | undefined): MailLang {
  const l = (language ?? 'en').slice(0, 2).toLowerCase();
  return (l in DICTS ? l : 'en') as MailLang;
}

export function mailTranslator(lang: MailLang): MailT {
  const dict = DICTS[lang];
  return (key, vars = {}) => (dict[key] ?? en[key]).replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`));
}
